// Copies the prompts, templates and demo brand kits into one TypeScript module for the app's
// server, so the deployed function never reads files from disk (Netlify doesn't ship files a
// function reads at runtime unless told to). prompts/, templates/ and brands/ stay the single
// source; this output is generated on every dev, build and test run and is not committed.
//
// Usage: npm run content
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import YAML from "yaml";
import { ROOT, PROMPTS_DIR, TEMPLATES_DIR, brandDir, kitDir } from "../spike/lib/paths.ts";

// Demo brands whose kits the server can use. Each needs kit/ and briefs.yaml.
const DEMO_BRANDS = ["half-acre-club"] as const;

const read = (path: string) => readFileSync(path, "utf8");

type BriefFile = { business_name: string; business_line: string; photos: { file: string; alt: string }[] };

const brands = Object.fromEntries(
  DEMO_BRANDS.map((brand) => {
    const kitFiles = Object.fromEntries(readdirSync(kitDir(brand)).sort().map((f) => [f, read(join(kitDir(brand), f))]));
    const briefs = YAML.parse(read(join(brandDir(brand), "briefs.yaml"))) as BriefFile;
    const photos = briefs.photos.map((p) => ({
      file: p.file,
      alt: p.alt.trim(),
      mediaType: p.file.endsWith(".png") ? "image/png" : "image/jpeg",
      base64: readFileSync(join(brandDir(brand), p.file)).toString("base64"),
    }));
    return [brand, { businessName: briefs.business_name, businessLine: briefs.business_line, kit: kitFiles, photos }];
  }),
);

const content = {
  prompts: { plan: read(join(PROMPTS_DIR, "plan.md")), write: read(join(PROMPTS_DIR, "write.md")), critique: read(join(PROMPTS_DIR, "critique.md")) },
  templatesManifest: read(join(TEMPLATES_DIR, "templates.json")),
  brands,
};

const out = `// GENERATED by scripts/bundle-content.ts from prompts/, templates/ and brands/. Do not edit.
// Rights reserved: prompts, fictional brands and design assets (see the README).
import "server-only";

export type DemoPhoto = { file: string; alt: string; mediaType: "image/jpeg" | "image/png"; base64: string };
export type DemoBrand = { businessName: string; businessLine: string; kit: Record<string, string>; photos: DemoPhoto[] };

export const DEMO_BRAND_IDS = ${JSON.stringify(DEMO_BRANDS)} as const;
export type DemoBrandId = (typeof DEMO_BRAND_IDS)[number];

export const CONTENT: {
  prompts: { plan: string; write: string; critique: string };
  templatesManifest: string;
  brands: Record<DemoBrandId, DemoBrand>;
} = ${JSON.stringify(content)};
`;

mkdirSync(join(ROOT, "server", "generated"), { recursive: true });
writeFileSync(join(ROOT, "server", "generated", "content.ts"), out);
console.log(`Bundled prompts, templates and ${DEMO_BRANDS.length} demo brand(s) into server/generated/content.ts (${Math.round(out.length / 1024)} KB)`);
