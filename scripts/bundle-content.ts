// Copies the prompts, templates and demo brand kits into one TypeScript module for the app's
// server, so the deployed function never reads files from disk (Netlify doesn't ship files a
// function reads at runtime unless told to). prompts/, templates/ and brands/ stay the single
// source; this output is generated on every dev, build and test run and is not committed.
//
// Usage: npm run content
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import YAML from "yaml";
import { ROOT, PROMPTS_DIR, TEMPLATES_DIR, brandDir, kitDir } from "../spike/lib/paths.ts";
import { TEMPLATE_IDS } from "../core/templates.ts";
import { wordmarkLines } from "../core/kit.ts";
import { DemoPostsSchema } from "../core/demo.ts";

// Demo brands whose kits the server can use. Each needs kit/ and briefs.yaml.
const DEMO_BRANDS = ["half-acre-club", "third-shift-slice", "hollis-ware"] as const;

const read = (path: string) => readFileSync(path, "utf8");

const PROMPT_NAMES = ["plan", "write", "critique", "read", "assemble", "intake", "compose", "change", "directions", "compose-bold", "art-critique", "sketch", "rebuild"] as const;

type BriefFile = { business_name: string; business_line: string; photos: { file: string; alt: string }[] };

// Static files the browser loads by URL (fonts and demo photos for rendered posts), copied to
// public/generated/ and not committed.
const PUBLIC_OUT = join(ROOT, "public", "generated");
rmSync(PUBLIC_OUT, { recursive: true, force: true });
mkdirSync(PUBLIC_OUT, { recursive: true });
cpSync(join(ROOT, "assets", "fonts"), join(PUBLIC_OUT, "fonts"), { recursive: true });

/** Copies brands/<brand>/logo.svg or logo.png next to the photos and returns its URL. */
function logoOf(brand: string): string | null {
  const file = ["logo.svg", "logo.png"].find((f) => existsSync(join(brandDir(brand), f)));
  if (!file) return null;
  cpSync(join(brandDir(brand), file), join(PUBLIC_OUT, brand, file));
  return `/generated/${brand}/${file}`;
}

const brands = Object.fromEntries(
  DEMO_BRANDS.map((brand) => {
    const kitFiles = Object.fromEntries(readdirSync(kitDir(brand)).sort().map((f) => [f, read(join(kitDir(brand), f))]));
    const briefs = YAML.parse(read(join(brandDir(brand), "briefs.yaml"))) as BriefFile;
    const photos = briefs.photos.map((p) => ({
      file: p.file,
      alt: p.alt.trim(),
      mediaType: p.file.endsWith(".png") ? "image/png" : "image/jpeg",
      base64: readFileSync(join(brandDir(brand), p.file)).toString("base64"),
    }));
    for (const p of briefs.photos) cpSync(join(brandDir(brand), p.file), join(PUBLIC_OUT, brand, p.file));
    // Precomputed posts, packed from a spike run by spike/pack-demo.ts. Optional until packed.
    const demoFile = join(brandDir(brand), "demo-posts.json");
    const demoPosts = existsSync(demoFile) ? DemoPostsSchema.parse(JSON.parse(read(demoFile))) : null;
    return [
      brand,
      {
        businessName: briefs.business_name,
        businessLine: briefs.business_line,
        kit: kitFiles,
        photos,
        wordmark: wordmarkLines(kitFiles, briefs.business_name),
        // The brand's own logo, designed for the demo; posts fall back to the type-built wordmark without one.
        logo: logoOf(brand),
        // The PNG logo's bytes, for the bold pass: the designer and the image model see the real logo.
        logoPng: existsSync(join(brandDir(brand), "logo.png")) ? readFileSync(join(brandDir(brand), "logo.png")).toString("base64") : null,
        demoPosts,
      },
    ];
  }),
);

const content = {
  prompts: Object.fromEntries(PROMPT_NAMES.map((name) => [name, read(join(PROMPTS_DIR, `${name}.md`))])),
  templatesManifest: read(join(TEMPLATES_DIR, "templates.json")),
  templates: Object.fromEntries(TEMPLATE_IDS.map((id) => [id, read(join(TEMPLATES_DIR, `${id}.html`))])),
  baseCss: read(join(TEMPLATES_DIR, "base.css")),
  neutralTokensCss: read(join(TEMPLATES_DIR, "neutral-tokens.css")),
  brands,
  // Specs' own brand kit, in the same format it makes for others (shown at /kit).
  specsKit: Object.fromEntries(readdirSync(kitDir("specs")).sort().map((f) => [f, read(join(kitDir("specs"), f))])),
};

const out = `// GENERATED by scripts/bundle-content.ts from prompts/, templates/ and brands/. Do not edit.
// Rights reserved: prompts, fictional brands and design assets (see the README).
import "server-only";

import type { DemoPosts } from "../../core/demo.ts";
import type { TemplateId } from "../../core/templates.ts";

export type DemoPhoto = { file: string; alt: string; mediaType: "image/jpeg" | "image/png"; base64: string };
export type DemoBrand = {
  businessName: string;
  businessLine: string;
  kit: Record<string, string>;
  photos: DemoPhoto[];
  wordmark: string[];
  /** URL of the brand's logo image, or null. */
  logo: string | null;
  /** The logo as base64 PNG, when the brand has a PNG logo. */
  logoPng: string | null;
  demoPosts: DemoPosts | null;
};

export const DEMO_BRAND_IDS = ${JSON.stringify(DEMO_BRANDS)} as const;
export type DemoBrandId = (typeof DEMO_BRAND_IDS)[number];

export const CONTENT: {
  prompts: Record<${PROMPT_NAMES.map((n) => JSON.stringify(n)).join(" | ")}, string>;
  templatesManifest: string;
  templates: Record<TemplateId, string>;
  baseCss: string;
  neutralTokensCss: string;
  brands: Record<DemoBrandId, DemoBrand>;
  specsKit: Record<string, string>;
} = ${JSON.stringify(content)};
`;

mkdirSync(join(ROOT, "server", "generated"), { recursive: true });
writeFileSync(join(ROOT, "server", "generated", "content.ts"), out);
console.log(`Bundled prompts, templates and ${DEMO_BRANDS.length} demo brand(s) into server/generated/content.ts (${Math.round(out.length / 1024)} KB)`);
